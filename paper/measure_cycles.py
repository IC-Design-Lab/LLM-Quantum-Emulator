"""Measure pipeline latency in clock cycles, by simulation, for every design in the
cycle-count table -- the 14 generated designs AND the 11 Chisel references.

WHY THIS EXISTS
---------------
Vivado reports do not contain cycle counts; none of the 70 reports in
results/vivado/reports mention cycles or latency. The only cycle counts in the
repository before this script were transcribed from images. Measuring both columns
here, by one procedure, replaces two transcriptions with one reproducible
measurement and lets the two be compared on equal terms.

WHAT IS MEASURED
----------------
    latency = (first rising clock edge at which io_out_valid samples high)
            - (first rising clock edge at which io_in_valid samples high)

io_in_valid is raised once and held, as the evaluation harness does. Data lines
carry a basis state; valid propagation in these pipelines does not depend on the
data, but a realistic stimulus costs nothing.

OUTPUT
------
    paper/data/cycles.csv        one row per design: measured cycles + provenance
    paper/data/cycles_check.txt  measured values against the transcribed table

The transcribed table (results/vivado/comparison.csv) is read ONLY to cross-check,
never as data. Its two columns come from two different sources -- the poster's
Chisel figures and a collaborator's run of the generated designs -- so it can
differ from a single-procedure measurement in two ways. A constant offset on every
row is a counting convention and cancels in the per-row delta; a row that does not
carry that constant is a real disagreement. The script separates the two, reports
both, and exits non-zero only for the second.

    python paper/measure_cycles.py              measure (25 ModelSim runs) + check
    python paper/measure_cycles.py --recheck    redo only the check, from cycles.csv
"""
from __future__ import annotations

import csv
import importlib.util
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import paperlib as L  # noqa: E402

# The mapping the paper's author stated. Used ONLY to check the mapping derived
# from the prompt files; if they disagree the script stops. Never used as data.
STATED_MAPPING = {
    "Circuit_00_v2": "Circuit0_06", "Circuit_01_v2": "Circuit0_17",
    "Circuit_02_v2": "Circuit0_2",  "Circuit_03_v2": "Circuit0_3",
    "Circuit_04_v2": "Circuit0_4",  "Circuit_05_v2": "Circuit0_5",
    "Circuit_06_v2": "Circuit1_0167", "Circuit_07_v2": "Circuit1_23",
    "Circuit_08_v2": "Circuit1_45", "QFT_v2": "QFT", "ShorFixed": "Shor",
}

# Designs that are a hand-corrected reference rather than model output.
CORRECTED = {"ShorFixed"}

TB_DIR = L.RAG / "new_circuits" / "tb"
SUP_DIR = L.RAG / "new_circuits" / "support"
TIMEOUT_CYCLES = 4000


def _import(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def testbench(top: str, ports, tag: str) -> str:
    ins = [(n, w) for n, d, w in ports if d == "input" and n not in ("clock", "reset", "io_in_valid")]
    outs = [(n, w) for n, d, w in ports if d == "output" and n != "io_out_valid"]
    names = {n for n, _, _ in ports}
    for req in ("clock", "reset", "io_in_valid", "io_out_valid"):
        if req not in names:
            L.die(f"{top}: port {req} not found; ports are {sorted(names)}")
    decl = "\n".join(f"  reg  [{w-1}:0] {n} = 0;" for n, w in ins) + "\n" + \
           "\n".join(f"  wire [{w-1}:0] {n};" for n, w in outs)
    conn = ",\n".join(f"    .{n}({n})" for n, _, _ in ports)
    first_in = ins[0][0] if ins else None
    drive = f"    {first_in} = 1;\n" if first_in else ""
    return f"""`timescale 1ns/1ps
// Cycle-count testbench, generated by paper/measure_cycles.py. Not a checker: it
// measures the distance in rising clock edges between io_in_valid and io_out_valid.
module tb_{tag};
  reg clock = 0, reset = 1, io_in_valid = 0;
  wire io_out_valid;
{decl}
  integer cyc = 0, t_in = -1, t_out = -1;

  {top} dut (
{conn}
  );

  always #5 clock = ~clock;

  always @(posedge clock) begin
    if (io_in_valid && t_in < 0) t_in = cyc;
    if (t_in >= 0 && io_out_valid && t_out < 0) begin
      t_out = cyc;
      $display("CYCLES: %0d", t_out - t_in);
      $finish;
    end
    if (cyc > {TIMEOUT_CYCLES}) begin
      $display("CYCLES: TIMEOUT");
      $finish;
    end
    cyc = cyc + 1;
  end

  initial begin
    // run_modelsim.ps1 reads the dump filename out of the testbench and
    // dereferences the match under Set-StrictMode, so this must be present.
    $dumpfile("{tag}.vcd"); $dumpvars(0, tb_{tag});
    repeat (4) @(posedge clock); #1 reset = 0;
    repeat (2) @(posedge clock); #1
{drive}    io_in_valid = 1;
  end
endmodule
"""


def run_sim(sim, design: Path, tb: Path, tb_top: str, library: str, label: str) -> str:
    """Run the ModelSim driver; return the transcript, falling back to the driver's
    own output when a compile failure leaves no transcript (same lesson as
    rag/simulate.py)."""
    with sim._Lock():
        if sim.TRANSCRIPT.exists():
            sim.TRANSCRIPT.unlink()
        inner = (f"& '{sim.DRIVER}' -Design '{design.resolve()}' -Library '{library}' "
                 f"-TB '{tb.resolve()}' -Top '{tb_top}' -Label '{label}'")
        proc = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass",
                               "-Command", inner], cwd=str(sim.SIM), capture_output=True,
                              text=True, errors="replace", timeout=900)
        log = L.read(sim.TRANSCRIPT) if sim.TRANSCRIPT.exists() else ""
        return log or (proc.stdout + proc.stderr)


def measure(sim, vg, name: str, kind: str, path: Path) -> dict:
    text = L.read(path)
    top = L.top_module(text)
    ports = L.module_ports(text, top)
    tag = f"cyc_{name}"
    TB_DIR.mkdir(parents=True, exist_ok=True)
    tb = TB_DIR / f"tb_{tag}.v"
    tb.write_text(testbench(top, ports, tag), encoding="utf-8")

    if kind in ("generated", "corrected_reference") and len(L.declared_modules(text)) == 1:
        states = len([n for n, d, _ in ports if d == "input" and n.endswith("_0")
                      and n.startswith("io_in_QSV")])
        nq = states.bit_length() - 1
        sup, _, missing = vg.support_for(text, top, nq)
        if missing:
            L.die(f"{name}: instantiates modules with no library definition: {sorted(missing)}")
        SUP_DIR.mkdir(parents=True, exist_ok=True)
        lib = SUP_DIR / f"{tag}_support.sv"
        lib.write_text(sup, encoding="utf-8")
        library = str(lib.resolve())
    else:
        library = "-"                     # self-contained: references and ShorFixed

    log = run_sim(sim, path, tb, f"tb_{tag}", library, tag)
    m = re.search(r"CYCLES:\s*(\d+|TIMEOUT)", log)
    cycles = None if not m or m.group(1) == "TIMEOUT" else int(m.group(1))
    if cycles is None:
        tail = "\n".join(log.strip().splitlines()[-8:])
        L.die(f"{name}: no cycle count measured.\n{tail}")
    return {"name": name, "kind": kind, "top_module": top, "cycles": cycles,
            "source_file": str(path.resolve().relative_to(L.REPO)),
            "pins": L.pin_count(ports)}


def cross_check(rows) -> int:
    """Compare the measured cycle counts against the transcribed table and
    write paper/data/cycles_check.txt. Returns the process exit code."""
    # ---- cross-check against the transcribed table --------------------------
    # The transcribed table's two columns come from two different sources: the
    # poster's Chisel figures and a collaborator's run of the generated designs.
    # Measuring both here under one procedure can differ from it in two ways:
    #
    #   a CONSTANT offset on every row -- a counting convention (which edge the
    #     valid-to-valid distance starts on). Harmless: it cancels in the delta.
    #   a row that does NOT share that constant -- a real disagreement about one
    #     design, which has to be understood before either number is used.
    #
    # Only the second is an error.
    trans = L.RESULTS / "vivado" / "comparison.csv"
    by = {r["name"]: r for r in rows}
    lines, comp = [], []
    if trans.exists():
        for t in csv.DictReader(trans.open(encoding="utf-8")):
            g, ref = t["rag_design"], t["poster_row"]
            comp.append({"gen": g, "ref": ref,
                         "gm": by[g]["cycles"], "gt": int(t["rag_cc"]),
                         "rm": by[ref]["cycles"], "rt": int(t["chisel_cc"])})

    if not comp:
        lines.append("(no transcribed table found; nothing to cross-check)")
        anomalies, k = [], None
    else:
        gen_off = {c["gm"] - c["gt"] for c in comp}
        k = gen_off.pop() if len(gen_off) == 1 else None
        lines.append("measured vs transcribed (results/vivado/comparison.csv)\n")
        lines.append(f"{'reference':<14} {'generated':<16} | "
                     f"{'MEASURED (one method)':^22} | {'TRANSCRIBED (two sources)':^24}")
        lines.append(f"{'':<14} {'':<16} | {'ref':>5} {'gen':>5} {'delta':>7} | "
                     f"{'ref':>5} {'gen':>5} {'delta':>7}")
        for c in comp:
            flag = "" if k is not None and c["rm"] - c["rt"] == k else "   <-- see below"
            lines.append(f"{c['ref']:<14} {c['gen']:<16} | {c['rm']:>5} {c['gm']:>5} "
                         f"{c['gm']-c['rm']:>+7} | {c['rt']:>5} {c['gt']:>5} "
                         f"{c['gt']-c['rt']:>+7}{flag}")

        def split(a, b):
            d = [x[a] - x[b] for x in comp]
            return (sum(1 for v in d if v == 0), sum(1 for v in d if v > 0),
                    sum(1 for v in d if v < 0))
        lines.append(f"\n  MEASURED split (exact/longer/shorter)    : {split('gm', 'rm')}")
        lines.append(f"  TRANSCRIBED split (exact/longer/shorter) : {split('gt', 'rt')}")

        if k is None:
            lines.append(f"\n  the generated column has no constant offset: "
                         f"{sorted({c['gm'] - c['gt'] for c in comp})}")
            anomalies = comp
        else:
            lines.append(f"\n  Generated column: measured = transcribed {k:+d} on every "
                         f"row -- a counting convention, which cancels in the delta.")
            anomalies = [c for c in comp if c["rm"] - c["rt"] != k]
            if anomalies:
                lines.append(f"  Reference column: the same {k:+d} on "
                             f"{len(comp) - len(anomalies)} of {len(comp)} rows. These "
                             f"do not share it, so the transcribed reference value is "
                             f"low by an extra cycle:")
                for c in anomalies:
                    lines.append(f"    {c['ref']:<14} measured {c['rm']}, transcribed "
                                 f"{c['rt']}  (offset {c['rm'] - c['rt']:+d}, "
                                 f"expected {k:+d})")
            else:
                lines.append(f"  Reference column: the same {k:+d} on every row.")

    text = "\n".join(lines)
    (L.DATA / "cycles_check.txt").write_text(text + "\n", encoding="utf-8")
    print("\n" + text)

    print("\nsources:")
    print(L.source(L.RAG / "new_circuits" / "verify_generated.py", "library harvest (support_for)"))
    print(L.source(L.RAG / "rag" / "simulate.py", "ModelSim driver + transcript"))
    print(L.source(L.OUT2, "generated designs"))
    print(L.source(L.CORPUS, "Chisel references (*_ground_truth.sv)"))
    print(L.source(L.OUT2, "mapping: <design>_prompt.txt SECTION 5"))

    if comp and k is None:
        print("\nSTOP: the measured generated column is not a constant offset from the "
              "transcribed one, so the difference is not a counting convention. "
              "cycles.csv was written; understand this before building Table II.",
              file=sys.stderr)
        return 1
    if anomalies:
        print(f"\nNOTE: {len(anomalies)} transcribed REFERENCE value(s) do not carry the "
              f"{k:+d} convention offset the other rows do "
              f"({', '.join(c['ref'] for c in anomalies)}). Table II uses the measured "
              f"values, which were produced for both columns by this script.")
    print("\nmeasured cycle counts written; see paper/data/cycles_check.txt")
    return 0


def main() -> int:
    # --recheck redoes only the comparison, from the cycles.csv of an earlier run.
    # The 25 simulations take a while and nothing about them depends on the table
    # they are compared against.
    if "--recheck" in sys.argv:
        out = L.DATA / "cycles.csv"
        if not out.exists():
            L.die(f"{out} not found -- run without --recheck first")
        rows = [dict(r, cycles=int(r["cycles"]), pins=int(r["pins"]))
                for r in csv.DictReader(out.open(encoding="utf-8"))]
        print(f"--recheck: {len(rows)} measurements read from "
              f"{out.relative_to(L.REPO)} (no simulation)")
        return cross_check(rows)

    os.chdir(L.RAG)                       # verify_generated.py uses relative paths
    sys.path.insert(0, str(L.RAG / "rag"))
    sys.path.insert(0, str(L.RAG))
    vg = _import(L.RAG / "new_circuits" / "verify_generated.py", "verify_generated")
    sim = _import(L.RAG / "rag" / "simulate.py", "simulate")
    if not sim.DRIVER.exists():
        L.die(f"ModelSim driver not found at {sim.DRIVER}")

    gen = L.generated_designs()
    refs = L.reference_designs()
    mapping = L.derive_mapping(gen)

    print("mapping derived from the prompts' SECTION 5 canonical text:")
    bad = []
    for stem, ref in sorted(mapping.items()):
        stated = STATED_MAPPING.get(stem)
        flag = "" if stated == ref else f"   <-- STATED {stated}"
        if stated != ref:
            bad.append(stem)
        print(f"  {stem:<16} -> {ref}{flag}")
    if set(STATED_MAPPING) != set(mapping) or bad:
        L.die(f"derived mapping disagrees with the stated mapping: {bad or 'row set differs'}")

    rows = []
    # ShorFixed is not a generated design: it is the 5-qubit reference with its
    # redundant trailing permutation removed by hand (see
    # ../docs/synthesis-provenance.md and corpus_v2/FINDING_shor_reference_bug.md).
    # It is measured like the rest, and labelled for what it is, so a reader does
    # not count it among the generated designs.
    kind_of = lambda stem: "corrected_reference" if stem in CORRECTED else "generated"
    todo = [(s, kind_of(s), p) for s, p in gen] + \
           [(n, "reference", p) for n, p in refs.items()]
    print(f"\nmeasuring {len(todo)} designs (ModelSim, serialised)")
    for i, (name, kind, path) in enumerate(todo, 1):
        r = measure(sim, vg, name, kind, path)
        r["reference_of"] = mapping.get(name, "")
        rows.append(r)
        print(f"  [{i:>2}/{len(todo)}] {kind:<9} {name:<16} top={r['top_module']:<24} "
              f"cycles={r['cycles']}", flush=True)

    out = L.DATA / "cycles.csv"
    L.write_csv(out, rows)
    print(f"\nwrote {out.relative_to(L.REPO)}")

    return cross_check(rows)


if __name__ == "__main__":
    raise SystemExit(main())
