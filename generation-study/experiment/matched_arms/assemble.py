"""Matched-arms payload assembly: Slot 1 (circuit) + Slot 2 (hardware knowledge)
+ Slot 3 (task instruction).

Design invariant (do not violate):
  - Slot 1 is the ONLY thing that varies by input_format (python vs json).
  - Slot 2 is the ONLY thing that varies by prompt_level, and is IDENTICAL
    across both format arms at a given level -- slot2_attachments() below
    does not take input_format as a parameter at all, so this is guaranteed
    structurally, not just by convention.
  - Slot 3 is constant across format x level x model x run for a given
    circuit. It DOES vary by circuit (module name) and would vary by
    datapath width for a future circuit family (QFT/Shor) -- that is a
    per-datapath-width constant, not a confound, since it is still constant
    across every axis this experiment actually compares.

These matched-arm runs use different Slot 3 wording than the old
full.md/medium.md/sparse.md templates that produced the earlier 112 runs in
results.csv. The two sets are NOT directly poolable -- old data is the
taxonomy foundation, these new runs are the format comparison. Keep them
separate in analysis.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent          # experiment/matched_arms
EXPERIMENT_DIR = ROOT.parent                     # experiment
REPO_ROOT = EXPERIMENT_DIR.parent                # llm-verilog

PYTHON_SPECS = ROOT / "python_specs"
JSON_SPECS = ROOT / "json_specs"
SLOT2_DIR = ROOT / "slot2"
ARCHITECTURE_RULES = SLOT2_DIR / "architecture_rules.md"
PIPELINES_DIR = SLOT2_DIR / "pipelines"
PERM_HINTS_DIR = SLOT2_DIR / "perm_hints"

TWO_QUBIT_CIRCUITS = tuple(f"Circuit_{i:02d}" for i in range(9))
CIRCUITS = TWO_QUBIT_CIRCUITS + ("QFT", "Shor")
FORMATS = ("python", "json")
LEVELS = ("full", "medium", "medium_strict", "sparse")

# Each circuit belongs to a datapath family: how many amplitudes, how wide each
# real/imag signal is, and which canonical gate_library.json describes its
# gates. Slot 2's gate_library.json attachment and Slot 3's port list are both
# keyed off this -- everything else (pipeline/perm_hints paths, Slot1 paths)
# is keyed off the circuit name directly and needs no family lookup.
_FAMILY_OF_CIRCUIT = {c: "2qubit" for c in TWO_QUBIT_CIRCUITS}
_FAMILY_OF_CIRCUIT["QFT"] = "qft"
_FAMILY_OF_CIRCUIT["Shor"] = "shor"

# (num_amplitudes, bit_width, gate_library.json filename)
_FAMILY_DATAPATH = {
    "2qubit": (4, 16, "gate_library.json"),
    "qft": (8, 8, "gate_library_QFT.json"),
    "shor": (32, 8, "gate_library_Shor.json"),
}


def _family(circuit: str) -> str:
    try:
        return _FAMILY_OF_CIRCUIT[circuit]
    except KeyError:
        raise ValueError(f"unknown circuit {circuit!r} -- no datapath family registered")


def _gate_library_json_path(circuit: str) -> Path:
    _, _, filename = _FAMILY_DATAPATH[_family(circuit)]
    return REPO_ROOT / "gate_library" / filename


def slot1_path(circuit: str, input_format: str) -> Path:
    if input_format == "python":
        return PYTHON_SPECS / f"{circuit}.py"
    if input_format == "json":
        return JSON_SPECS / f"{circuit}.json"
    raise ValueError(f"unknown input_format {input_format!r}, expected one of {FORMATS}")


def _slot2_paths(circuit: str, level: str) -> list[Path]:
    """The exact Slot 2 attachment set for (circuit, level). Deliberately does
    NOT take input_format -- structurally impossible for this to vary by
    format, which is the guarantee requirement #2 asks for."""
    if level not in LEVELS:
        raise ValueError(f"unknown level {level!r}, expected one of {LEVELS}")
    paths: list[Path] = []
    if level in ("full", "medium", "medium_strict"):
        paths.append(_gate_library_json_path(circuit))
        paths.append(ARCHITECTURE_RULES)
    if level == "full":
        paths.append(PIPELINES_DIR / f"{circuit}_pipeline.json")
    if level == "medium":
        paths.append(PERM_HINTS_DIR / f"{circuit}_perm_hints.json")
    # medium_strict: gate_library.json + architecture_rules.md only (no pipeline, no perm hints)
    # sparse: nothing
    return paths


# Exact original 2-qubit port block (byte-for-byte -- this is what every
# Circuit_00..08 row in results_matched.csv was already generated against).
# Kept as a literal, not regenerated by _wrap_ports(), so a change to the
# wrapping algorithm below can never silently alter this and desync old vs
# new rows for the same 9 circuits the way the gate_library.json edit did.
_TWO_QUBIT_PORTS_BLOCK = """- Ports (all QSV signals are [15:0]):
  inputs:  clock, reset, io_in_QSV_0_0, io_in_QSV_0_1, io_in_QSV_1_0, io_in_QSV_1_1,
           io_in_QSV_2_0, io_in_QSV_2_1, io_in_QSV_3_0, io_in_QSV_3_1, io_in_valid
  outputs: io_out_QSV_0_0, io_out_QSV_0_1, io_out_QSV_1_0, io_out_QSV_1_1,
           io_out_QSV_2_0, io_out_QSV_2_1, io_out_QSV_3_0, io_out_QSV_3_1, io_out_valid"""


def _wrap_ports(names, label):
    """label + names wrapped to a readable width; continuation lines align
    under the first item (pure indent, label is never repeated)."""
    indent = " " * len(label)
    lines, cur = [], label
    for n in names:
        token = n + ", "
        if cur != (label if not lines else indent) and len(cur) + len(token) > 88:
            lines.append(cur.rstrip())
            cur = indent
        cur += token
    lines.append(cur.rstrip().rstrip(","))
    return "\n".join(lines)


def _port_list_block(num_amplitudes: int, bit_width: int) -> str:
    """Builds the 'inputs: ... / outputs: ...' block for a given datapath,
    in the same visual style as the hand-written 2-qubit template."""
    qsv_in = [f"io_in_QSV_{i}_{s}" for i in range(num_amplitudes) for s in (0, 1)]
    qsv_out = [f"io_out_QSV_{i}_{s}" for i in range(num_amplitudes) for s in (0, 1)]
    inputs = _wrap_ports(["clock", "reset"] + qsv_in + ["io_in_valid"], "  inputs:  ")
    outputs = _wrap_ports(qsv_out + ["io_out_valid"], "  outputs: ")
    return f"- Ports (all QSV signals are [{bit_width - 1}:0], {num_amplitudes} amplitudes):\n{inputs}\n{outputs}"


def slot3_instruction(circuit: str) -> str:
    """Constant task instruction, module name hardcoded per-circuit so both
    format arms get it identically (the Python spec only carries the module
    name as a comment; stating it here removes that asymmetry).

    The port list is generated per-circuit-family: 2-qubit circuits get
    4 amplitudes / 16-bit; QFT gets 8 amplitudes / 8-bit; Shor gets 32
    amplitudes / 8-bit. This varies by datapath width, not by format or
    prompt level -- still constant across every axis this experiment
    actually compares for a given circuit.
    """
    family = _family(circuit)
    if family == "2qubit":
        ports_block = _TWO_QUBIT_PORTS_BLOCK
    else:
        num_amplitudes, bit_width, _ = _FAMILY_DATAPATH[family]
        ports_block = _port_list_block(num_amplitudes, bit_width)
    return f"""Generate a synthesizable SystemVerilog top-level module implementing the quantum
circuit described in the attached circuit specification.

Requirements:
- Module name: exactly `{circuit}`.
{ports_block}
- Implement the gate sequence from the circuit specification's operations list, in order.
- Use any attached reference materials (gate library, architecture rules, pipeline,
  or permutation hints) if present. For anything not attached, rely on your own
  knowledge of standard conventions for this kind of hardware.
- Named port mapping only (no positional connections). No initial blocks, no
  hardcoded delays (#N), no $display/$monitor statements, no unused or dead wires.
- Output only the Verilog module -- no explanation, no prose, just the code.
"""


def expected_attachment_names(circuit: str, level: str) -> list[str]:
    return [p.name for p in _slot2_paths(circuit, level)]


def build_payload(circuit: str, input_format: str, level: str):
    """Returns (system_instruction, contents, attachment_names).

    Raises AssertionError if the assembled attachment set doesn't exactly
    match what this level is supposed to carry (pre-flight guard #1), or if
    a sparse run somehow ends up with a non-empty attachment set (guard,
    belt-and-suspenders on top of the level-table check).
    """
    slot1 = slot1_path(circuit, input_format)
    if not slot1.exists():
        raise FileNotFoundError(f"Slot 1 spec missing: {slot1}")

    slot2_paths = _slot2_paths(circuit, level)
    for p in slot2_paths:
        if not p.exists():
            raise FileNotFoundError(f"Slot 2 attachment missing: {p}")

    actual_names = [p.name for p in slot2_paths]
    expected_names = expected_attachment_names(circuit, level)
    assert actual_names == expected_names, (
        f"PRE-FLIGHT ASSERTION FAILED for {circuit}/{input_format}/{level}: "
        f"attachment set {actual_names} != expected {expected_names}. Refusing to send."
    )
    if level == "sparse":
        assert actual_names == [], (
            f"PRE-FLIGHT ASSERTION FAILED: sparse must carry ZERO attachments, "
            f"got {actual_names}. Refusing to send."
        )

    system_instruction = slot3_instruction(circuit)

    parts = [f"Circuit specification ({slot1.name}):\n```\n{slot1.read_text(encoding='utf-8')}\n```"]
    for p in slot2_paths:
        lang = "json" if p.suffix == ".json" else "markdown" if p.suffix == ".md" else ""
        parts.append(f"{p.name}:\n```{lang}\n{p.read_text(encoding='utf-8')}\n```")
    contents = "\n\n".join(parts)

    return system_instruction, contents, actual_names


def assert_identical_across_formats(circuit: str, level: str):
    """Structural check for guard #2: both format arms at a given level must
    attach identical Slot 2 files. True by construction since _slot2_paths()
    never takes input_format -- this just re-derives it twice and diffs, as
    an explicit executable proof rather than relying on the reader trusting
    the function signature."""
    a = expected_attachment_names(circuit, level)
    b = expected_attachment_names(circuit, level)
    assert a == b, f"Slot 2 attachment sets diverged for {circuit}/{level}: {a} vs {b}"
    return a
